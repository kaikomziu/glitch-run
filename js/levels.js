//       P スタート / S バネ / F チェックポイント / G ゴール
const TILE = 24;

function buildLevel(def) {
  const { W, H } = def;
  const g = Array.from({ length: H }, () => Array(W).fill("."));
  const L = {
    fill(c0, r0, c1, r1, ch) {
      for (let r = r0; r <= r1; r++)
        for (let c = c0; c <= c1; c++)
          if (r >= 0 && r < H && c >= 0 && c < W) g[r][c] = ch;
    },
    set(c, r, ch) { if (r >= 0 && r < H && c >= 0 && c < W) g[r][c] = ch; },
    border(ch = "#", ceiling = true) {
      if (ceiling) this.fill(0, 0, W - 1, 0, ch);
      this.fill(0, 0, 0, H - 1, ch);
      this.fill(W - 1, 0, W - 1, H - 1, ch);
    },
  };
  def.build(L);
  const lvl = { ...def, grid: g, springs: [], checks: [], goal: null, start: null };
  for (let r = 0; r < H; r++) for (let c = 0; c < W; c++) {
    const ch = g[r][c];
    if (ch === "P") { lvl.start = { c, r }; g[r][c] = "."; }
    else if (ch === "S") { lvl.springs.push({ c, r, anim: 0 }); g[r][c] = "."; }
    else if (ch === "F") { lvl.checks.push({ c, r, on: false }); g[r][c] = "."; }
    else if (ch === "G") { lvl.goal = { c, r }; g[r][c] = "."; }
  }
  return lvl;
}

